import { test, expect } from '@playwright/test';

test('付费副标题只说明当前实际绘制的系列', async ({ page }) => {
  await page.request.post('/api/auth/register', { data: { username: `paycopy${Date.now()}`, displayName: '图表测试', password: 'test-password-123' } });
  await page.goto('/');
  const openReport = page.getByRole('button', { name: '完整报告', exact: true });
  await expect(openReport.first()).toBeVisible();
  await openReport.first().click();
  const card = page.locator('[data-chart-id="payment"]');
  const svg = card.locator('svg[role="img"]');
  await card.getByLabel('付费指标', { exact: true }).selectOption('rate');
  await expect(svg).not.toContainText('柱为');
  await expect(svg).toContainText('线为');
  await card.getByLabel('付费指标', { exact: true }).selectOption('payers');
  await expect(svg).toContainText('柱为');
  await expect(svg).not.toContainText('线为');
  await card.getByLabel('付费指标', { exact: true }).selectOption('both');
  await expect(svg).toContainText('柱为');
  await expect(svg).toContainText('线为');
});

test('图表查看复用设置、放大和本机持久化', async ({ page }) => {
  test.setTimeout(120000);
  await page.request.post('/api/auth/register', { data: { username: `charts${Date.now()}`, displayName: '图表测试', password: 'test-password-123' } });
  await page.goto('/');
  const openReport = page.getByRole('button', { name: '完整报告', exact: true });
  await expect(openReport.first()).toBeVisible();
  await openReport.first().click();
  const section = page.getByRole('region', { name: '图表查看', exact: true });
  await expect(section).toBeVisible();
  await expect(section.locator('.op-chart-card')).toHaveCount(5);
  await section.getByRole('button', { name: '设置', exact: true }).click();
  await expect(section.getByRole('group', { name: '图表设置', exact: true })).toBeVisible();
  const settings = section.getByRole('group', { name: '图表设置', exact: true });
  await settings.getByRole('button', { name: '渠道表现下移', exact: true }).click();
  await expect(section.locator('.op-chart-card').first()).toHaveAttribute('data-chart-id', 'weekday');
  for (const [label, value] of [['渠道指标','revenue'],['渠道类型','bar'],['渠道排序','asc'],['周内指标','newUsers'],['周内类型','line'],['留存类型','area'],['付费指标','rate'],['付费时间粒度','week'],['累计指标','revenue'],['累计类型','line'],['累计时间粒度','month']]) await settings.getByLabel(label,{exact:true}).selectOption(value);
  await section.locator('[data-chart-id="weekday"]').getByRole('button',{name:'隐藏',exact:true}).click();
  await expect(section.locator('.op-chart-card')).toHaveCount(4);
  await settings.getByRole('checkbox',{name:'周内规律',exact:true}).check();
  await expect(section.locator('.op-chart-card')).toHaveCount(5);
  const before = await (await page.request.get('/api/bootstrap')).json();
  const channel = section.locator('[data-chart-id="channel"]');
  const trigger = channel.getByRole('button', { name: '放大查看', exact: true });
  await trigger.click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await dialog.getByRole('textbox', { name: '主标题', exact: true }).fill('渠道观察');
  await dialog.getByRole('textbox', { name: '观察备注', exact: true }).fill('版本更新期间');
  await dialog.getByLabel('配色方案', { exact: true }).selectOption('warm');
  await expect(dialog.locator('svg[role=img]')).toHaveAttribute('aria-label', /渠道观察/);
  const downloadPromise = page.waitForEvent('download');
  await dialog.getByRole('button', { name: /PNG/ }).click();
  const download = await downloadPromise;
  await download.saveAs('artifacts/chart-viewer-channel.png');
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await expect(channel.getByRole('img')).toHaveAttribute('aria-label', /渠道观察/);
  await section.screenshot({path:'artifacts/chart-viewer-light.png'});
  await page.reload();
  const reopen = page.getByRole('button', { name: '完整报告', exact: true });
  await expect(reopen.first()).toBeVisible();
  await reopen.first().click();
  await expect(section.locator('[data-chart-id="channel"]').getByRole('img')).toHaveAttribute('aria-label', /渠道观察/);
  await page.getByRole('button', { name: '显示设置', exact: true }).click();
  await page.getByRole('button', { name: '夜间', exact: true }).click();
  await page.getByRole('button', { name: '关闭', exact: true }).last().click();
  await section.screenshot({ path: 'artifacts/chart-viewer-dark.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await section.screenshot({ path: 'artifacts/chart-viewer-390.png' });
  await page.setViewportSize({width:1280,height:720});
  await expect(section.locator('[data-chart-id="channel"] svg[role="img"]')).toHaveAttribute('aria-label',/渠道观察/);
  await page.emulateMedia({media:'print'});
  await expect(section.locator('.op-card-tools').first()).toBeHidden();
  await expect(section.locator('.op-export').first()).toBeHidden();
  await section.screenshot({path:'artifacts/chart-viewer-print.png'});
  await page.emulateMedia({media:'screen'});
  const after = await (await page.request.get('/api/bootstrap')).json();
  expect(after.tasks.length).toBe(before.tasks.length);
  expect(after.wallet).toEqual(before.wallet);
  expect((await (await page.request.get('/__e2e/stats')).json()).calls).toBe(0);
});

