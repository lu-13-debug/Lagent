import { test, expect } from '@playwright/test';
test('仅简洁页面，保留主题切换且不自动收费', async ({ page }, info) => {
  test.setTimeout(90000);
  await page.request.post('/api/auth/register', { data: { username: `appearance${Date.now()}`, displayName: '外观测试', password: 'test-password-123' } });
  await page.goto('/');
  await expect(page.locator('html')).toHaveAttribute('data-view', 'concise');
  await expect(page.locator('.concise-workspace')).toBeVisible();
  await expect(page.locator('.page-heading')).toHaveCount(0);
  await page.screenshot({ path: info.outputPath('concise-initial.png'), fullPage: true });
  const before = await (await page.request.get('/api/bootstrap')).json();
  await page.getByRole('button', { name: '显示设置', exact: true }).click();
  await expect(page.getByRole('button', { name: '简洁版', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: '正常版', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '白天', exact: true }).click();
  await page.getByRole('button', { name: '关闭', exact: true }).last().click();
  await expect(page.locator('html')).toHaveAttribute('data-view', 'concise');
  await expect(page.locator('.concise-workspace')).toBeVisible();
  await expect(page.locator('.page-heading')).toHaveCount(0);
  await expect(page.locator('.concise-current')).toContainText('预置示例 · 不扣费');
  await page.screenshot({ path: info.outputPath('concise-day.png'), fullPage: true });
  await page.getByLabel('分析目标', { exact: true }).fill('检查最近一周的收入变化');
  await page.getByRole('button', { name: '开始分析', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('dialog')).toContainText('开始一次新的分析');
  await page.getByRole('dialog').getByRole('checkbox').check();
  await page.getByRole('dialog').getByRole('button', { name: /下一步/ }).click();
  await expect(page.getByRole('dialog').getByLabel('分析目标', { exact: true })).toHaveValue('检查最近一周的收入变化');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '查看执行详情', exact: true }).click();
  await expect(page.getByRole('complementary', { name: 'AI 工作动态' })).toBeVisible();
  await page.getByRole('complementary', { name: 'AI 工作动态' }).getByRole('button', { name: '关闭 AI 动态', exact: true }).click();
  await expect(page.getByRole('complementary', { name: 'AI 工作动态' })).toBeHidden();
  await page.getByRole('button', { name: '完整报告', exact: true }).click();
  await expect(page.locator('.full-report')).toBeVisible();
  await page.getByRole('button', { name: '返回简洁首页', exact: true }).click();
  await expect(page.locator('.concise-workspace')).toBeVisible();
  await page.getByRole('button', { name: '显示设置', exact: true }).click();
  await page.getByRole('button', { name: '夜间', exact: true }).click();
  await page.getByRole('button', { name: '关闭', exact: true }).last().click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-view', 'concise');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.screenshot({ path: info.outputPath('concise-night.png'), fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  await expect(page.locator('.concise-workspace')).toBeVisible();
  await expect(page.locator('.sidebar')).toBeHidden();
  const header = await page.locator('.topbar').boundingBox();
  const toolbar = await page.locator('.page-toolbar').boundingBox();
  expect(header!.y + header!.height).toBeLessThanOrEqual(toolbar!.y + 1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: info.outputPath('concise-mobile.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '打开导航', exact: true }).click();
  await expect(page.locator('.sidebar')).toBeVisible();
  await page.locator('.sidebar').getByRole('button', { name: '收起导航', exact: true }).click();
  await expect(page.locator('.sidebar')).toBeHidden();
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.getByRole('button', { name: '显示设置', exact: true }).click();
  await page.getByRole('button', { name: '跟随系统', exact: true }).click();
  await page.emulateMedia({ colorScheme: 'light' });
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.emulateMedia({ colorScheme: 'dark' });
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.getByRole('button', { name: '关闭', exact: true }).last().click();
  await expect(page.locator('html')).toHaveAttribute('data-view', 'concise');
  await expect(page.locator('.page-heading')).toHaveCount(0);
  const after = await (await page.request.get('/api/bootstrap')).json();
  expect(after.tasks.length).toBe(before.tasks.length); expect(after.wallet).toEqual(before.wallet);
});
